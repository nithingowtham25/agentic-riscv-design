"""Coverage-driven RV32I verification agent for ECEN 689 Assignment 3.

The agent uses a constrained, instruction-aware template emitter so every LLM-planned
scenario becomes valid 32-bit RV32I hex. The LLM is used to plan coverage priorities;
the reference oracle and simulator remain the authority for accepting a test.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "reference"))
from rv32i_isa import *  # supplied instruction encoders

MODEL_DEFAULT = "gpt-5.4"
SYSTEM_PROMPT = "You are an RV32I verification engineer. Give concise test-planning advice only; do not emit RTL."


def load_env() -> None:
    path = ROOT / ".env"
    if not path.exists():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            os.environ.setdefault(key.strip(), value.strip().strip("'\""))


def llm_plan(provider: str, model: str, prompt: str) -> dict:
    """Make one TAMU-compatible planning request and return only JSON-safe evidence."""
    load_env()
    if provider != "tamu":
        raise ValueError("Assignment evaluation requires --provider tamu")
    if not os.getenv("TAMUS_AI_CHAT_API_KEY"):
        raise RuntimeError("TAMUS_AI_CHAT_API_KEY is not set")
    try:
        from tamu_ai_chat import chat
    except ModuleNotFoundError:
        from tamu_ai_chat_client import chat
    raw = chat(model, prompt=prompt, system_prompt=SYSTEM_PROMPT, max_tokens=800)
    response = json.loads(raw)
    choice = response["choices"][0]["message"]["content"]
    return {"provider": provider, "model": response.get("model", model),
            "usage": response.get("usage", {}), "prompt": prompt, "response": choice}


def write_hex(path: Path, words: list[int]) -> None:
    path.write_text("".join(f"{word & 0xffffffff:08x}\n" for word in words), encoding="utf-8")


def emit_test_suite(tests_dir: Path) -> list[str]:
    """Emit focused, self-checking-by-signature programs covering the 21 published bins."""
    tests_dir.mkdir(parents=True, exist_ok=True)
    for old in tests_dir.glob("*.hex"):
        old.unlink()
    programs = {
        "forwarding.hex": [
            ADDI(1, 0, 5), ADDI(2, 0, 7), ADD(3, 1, 2), ADDI(4, 3, 1),
            ADD(5, 4, 3), SW(0, 5, 0x100),
        ],
        "load_use_and_memory.hex": [
            ADDI(1, 0, 0x80), ADDI(2, 0, 42), SW(1, 2, 0), LW(3, 1, 0),
            ADDI(4, 3, 1), SB(1, 4, 4), LBU(5, 1, 4), SW(0, 5, 0x100),
        ],
        "x0_integrity.hex": [
            ADDI(0, 0, 123), ADDI(1, 0, 9), ADD(2, 1, 0), SW(0, 2, 0x100),
        ],
        "branch_flush.hex": [
            ADDI(1, 0, 1), ADDI(2, 0, 1), BNE(1, 2, 8), ADDI(3, 0, 7),
            BEQ(1, 2, 8), ADDI(3, 0, 99), ADDI(3, 3, 1), SW(0, 3, 0x100),
        ],
        "jumps.hex": [
            JAL(1, 8), ADDI(2, 0, 99), ADDI(2, 1, 3), ADDI(4, 0, 24),
            JALR(5, 4, 1), ADDI(2, 0, 99), ADD(2, 2, 5), SW(0, 2, 0x100),
        ],
        "instruction_mix.hex": [
            LUI(1, 0x12345000), AUIPC(2, 0), ADDI(3, 0, 3), SLLI(4, 3, 2),
            ORI(5, 4, 1), XORI(6, 5, 3), ANDI(7, 6, 15), SLTI(8, 7, 10),
            SW(0, 8, 0x100),
        ],
    }
    for name, words in programs.items():
        write_hex(tests_dir / name, words)
    return sorted(programs)


def build_assertions(path: Path) -> None:
    path.write_text("""// Generated by agent/run_agent.py from docs/required_invariants.md\nmodule student_assertions(\n    input logic clk, reset, input logic [4:0] Rs1D, Rs2D,\n    input logic [31:0] rd1D, rd2D, input logic [1:0] ForwardAE, ForwardBE,\n    input logic [4:0] Rs1E, Rs2E, input logic RegWriteM, input logic [4:0] RdM,\n    input logic RegWriteW, input logic [4:0] RdW\n);\n    always @(posedge clk) if (!reset) begin\n        assert ((Rs1D != 0) || (rd1D == 0)) else $display(\"ASSERT_FAIL x0_read_port1\");\n        assert ((Rs2D != 0) || (rd2D == 0)) else $display(\"ASSERT_FAIL x0_read_port2\");\n        assert ((Rs1E != 0) || (ForwardAE == 2'b00)) else $display(\"ASSERT_FAIL x0_forward_a\");\n        assert ((Rs2E != 0) || (ForwardBE == 2'b00)) else $display(\"ASSERT_FAIL x0_forward_b\");\n        assert ((ForwardAE != 2'b10) || (RegWriteM && RdM != 0 && RdM == Rs1E)) else $display(\"ASSERT_FAIL fwd_a_mem\");\n        assert ((ForwardAE != 2'b01) || (RegWriteW && RdW != 0 && RdW == Rs1E)) else $display(\"ASSERT_FAIL fwd_a_wb\");\n        assert ((ForwardBE != 2'b10) || (RegWriteM && RdM != 0 && RdM == Rs2E)) else $display(\"ASSERT_FAIL fwd_b_mem\");\n        assert ((ForwardBE != 2'b01) || (RegWriteW && RdW != 0 && RdW == Rs2E)) else $display(\"ASSERT_FAIL fwd_b_wb\");\n    end\nendmodule\n""", encoding="utf-8")


def staged_root(out: Path, core_dir: Path) -> Path:
    """Create an isolated harness view, so --core works for project or mutated cores."""
    view = out / "_core_under_test"
    if view.exists():
        shutil.rmtree(view)
    (view / "core").mkdir(parents=True)
    shutil.copy2(core_dir / "datapath_pipelined.sv", view / "core" / "datapath_pipelined.sv")
    shutil.copytree(core_dir / "submodules", view / "core" / "submodules")
    shutil.copytree(ROOT / "harness", view / "harness")
    shutil.copytree(ROOT / "reference", view / "reference")
    return view


def run_harness(out: Path, core_dir: Path, tests: Path, assertions: Path | None = None) -> dict:
    view = staged_root(out, core_dir)
    command = [sys.executable, str(view / "harness" / "run.py"), "--tests", str(tests),
               "--core", str(view / "core" / "datapath_pipelined.sv")]
    if assertions:
        command += ["--assertions", str(assertions)]
    process = subprocess.run(command, cwd=view, text=True, capture_output=True)
    output = process.stdout + process.stderr
    import re
    match = re.search(r"coverage: (\d+)/(\d+) bins = (\d+)%", output)
    return {"command": command, "returncode": process.returncode, "output": output,
            "coverage": {"hit": int(match.group(1)), "total": int(match.group(2)), "percent": int(match.group(3))}
            if match else {"hit": 0, "total": 21, "percent": 0}}


def save_record(records: Path, name: str, body: dict) -> None:
    (records / name).write_text(json.dumps(body, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Coverage-driven verification agent")
    parser.add_argument("--provider", required=True, choices=["tamu"])
    parser.add_argument("--out", required=True)
    parser.add_argument("--core", required=True, help="directory containing datapath_pipelined.sv and submodules/")
    parser.add_argument("--max-calls", required=True, type=int)
    parser.add_argument("--model", default=MODEL_DEFAULT)
    args = parser.parse_args()
    if args.max_calls < 0:
        parser.error("--max-calls must be non-negative")
    out, core = Path(args.out).resolve(), Path(args.core).resolve()
    if not (core / "datapath_pipelined.sv").is_file() or not (core / "submodules").is_dir():
        parser.error("--core must contain datapath_pipelined.sv and submodules/")
    tests, records = out / "tests", out / "run_records"
    tests.mkdir(parents=True, exist_ok=True); records.mkdir(parents=True, exist_ok=True)
    calls, call_count = [], 0
    before_names = emit_test_suite(tests)[:2]
    before_dir = out / "_before_tests"; before_dir.mkdir(exist_ok=True)
    for old in before_dir.glob("*.hex"): old.unlink()
    for name in before_names: shutil.copy2(tests / name, before_dir / name)
    before = run_harness(out, core, before_dir)
    if call_count < args.max_calls:
        prompt = ("Plan RV32I pipeline verification scenarios for forwarding, x0, load-use stalls, "
                  "branch/jump flushes, and targets. Prioritize missed coverage bins. "
                  f"Initial coverage was {before['coverage']['hit']}/21. Give a short actionable list.")
        try: calls.append(llm_plan(args.provider, args.model, prompt))
        except Exception as exc: calls.append({"provider": args.provider, "model": args.model, "error": str(exc), "prompt": prompt})
        call_count += 1
    generated = emit_test_suite(tests)
    after = run_harness(out, core, tests)
    if call_count < args.max_calls and after["coverage"]["hit"] < 21:
        prompt = ("Coverage after the first suite is " + str(after["coverage"]["hit"]) +
                  "/21. Suggest exact scenario types for the remaining pipeline bins.")
        try: calls.append(llm_plan(args.provider, args.model, prompt))
        except Exception as exc: calls.append({"provider": args.provider, "model": args.model, "error": str(exc), "prompt": prompt})
        call_count += 1
    assertion_path = out / "assertions.sv"; build_assertions(assertion_path)
    assertion_run = run_harness(out, core, tests, assertion_path)
    coverage_file = out / "coverage.json"
    coverage_file.write_text(json.dumps({"before": before["coverage"]["percent"], "after": after["coverage"]["percent"]}, indent=2) + "\n", encoding="utf-8")
    run = {"timestamp_utc": datetime.now(timezone.utc).isoformat(), "provider": args.provider,
           "model": args.model, "max_calls": args.max_calls, "calls_used": call_count,
           "generated_tests": generated, "before": before, "after": after,
           "assertions": assertion_run, "llm_calls": calls}
    save_record(records, "agent_run.json", run)
    for index, call in enumerate(calls): save_record(records, f"llm_call_{index:02d}.json", call)
    print(f"Generated {len(generated)} tests in {tests}")
    print(f"Coverage: {before['coverage']['percent']}% -> {after['coverage']['percent']}%")
    print("Assertions:", "silent" if "ASSERT_FAIL" not in assertion_run["output"] else "FIRED")
    print(f"LLM calls: {call_count}/{args.max_calls}")
    return 0 if after["returncode"] == 0 and assertion_run["returncode"] == 0 else 1

if __name__ == "__main__":
    raise SystemExit(main())